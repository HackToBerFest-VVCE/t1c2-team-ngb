-- Reproducible, read-only review of the connected NVD-origin table.
-- Manually executed with THREATLENS_APP_ROLE on 2026-10-25; not CoCo output.
-- The app excludes rejected CVEs when creating its 160,846-row active set.

DESC TABLE THREATLENS_DB.THREATLENS.VULNERABILITIES;

SELECT
  COUNT(*) AS ROWS_TOTAL,
  COUNT(DISTINCT CVE_ID) AS DISTINCT_CVES,
  COUNT_IF(UPPER(COALESCE(DESCRIPTION, '')) LIKE 'REJECTED REASON:%') AS REJECTED_ROWS,
  COUNT_IF(CVSS_SCORE IS NULL) AS NULL_CVSS,
  COUNT_IF(SEVERITY IS NULL) AS NULL_SEVERITY,
  COUNT_IF(CWE IS NULL) AS NULL_CWE,
  COUNT_IF(AFFECTED_PRODUCTS IS NULL) AS NULL_PRODUCTS,
  MIN(PUBLISHED) AS FIRST_PUBLISHED,
  MAX(PUBLISHED) AS LAST_PUBLISHED
FROM THREATLENS_DB.THREATLENS.VULNERABILITIES;

SELECT
  COALESCE(NULLIF(UPPER(TRIM(SEVERITY)), ''), 'UNKNOWN') AS SEVERITY,
  COUNT(*) AS RECORDS
FROM THREATLENS_DB.THREATLENS.VULNERABILITIES
WHERE UPPER(COALESCE(DESCRIPTION, '')) NOT LIKE 'REJECTED REASON:%'
GROUP BY 1
ORDER BY RECORDS DESC;

SELECT TRIM(VALUE::STRING) AS CWE_VALUE, COUNT(*) AS RECORDS
FROM THREATLENS_DB.THREATLENS.VULNERABILITIES,
  LATERAL FLATTEN(INPUT => SPLIT(REPLACE(COALESCE(CWE, ''), ';', ','), ','))
WHERE UPPER(COALESCE(DESCRIPTION, '')) NOT LIKE 'REJECTED REASON:%'
  AND TRIM(VALUE::STRING) <> ''
GROUP BY 1
ORDER BY RECORDS DESC
LIMIT 10;

SELECT CVE_ID, CVSS_SCORE, SEVERITY, CWE, PUBLISHED, SOURCE_URL
FROM THREATLENS_DB.THREATLENS.VULNERABILITIES
WHERE UPPER(COALESCE(DESCRIPTION, '')) NOT LIKE 'REJECTED REASON:%'
ORDER BY PUBLISHED DESC NULLS LAST
LIMIT 5;
