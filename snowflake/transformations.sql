-- Example reviewable transform after staging NVD 2.0 JSON into a table with
-- columns CVE_ID, DESCRIPTION, PUBLISHED, LAST_MODIFIED, CVSS_SCORE, SEVERITY,
-- CWE, AFFECTED_PRODUCTS, SOURCE_URL. Adjust identifiers to actual staging schema.
MERGE INTO THREATLENS.VULNERABILITIES AS target
USING (
  SELECT UPPER(TRIM(CVE_ID)) AS CVE_ID,
         NULLIF(TRIM(DESCRIPTION), '') AS DESCRIPTION,
         TRY_TO_TIMESTAMP_TZ(PUBLISHED) AS PUBLISHED,
         TRY_TO_TIMESTAMP_TZ(LAST_MODIFIED) AS LAST_MODIFIED,
         TRY_TO_DOUBLE(CVSS_SCORE) AS CVSS_SCORE,
         UPPER(COALESCE(NULLIF(TRIM(SEVERITY), ''), 'UNKNOWN')) AS SEVERITY,
         NULLIF(TRIM(CWE), '') AS CWE,
         NULLIF(TRIM(AFFECTED_PRODUCTS), '') AS AFFECTED_PRODUCTS,
         SOURCE_URL
  FROM THREATLENS.NVD_STAGING
  QUALIFY ROW_NUMBER() OVER (PARTITION BY UPPER(TRIM(CVE_ID)) ORDER BY TRY_TO_TIMESTAMP_TZ(LAST_MODIFIED) DESC NULLS LAST) = 1
) AS source
ON target.CVE_ID = source.CVE_ID
WHEN MATCHED THEN UPDATE SET
  DESCRIPTION=source.DESCRIPTION, PUBLISHED=source.PUBLISHED,
  LAST_MODIFIED=source.LAST_MODIFIED, CVSS_SCORE=source.CVSS_SCORE,
  SEVERITY=source.SEVERITY, CWE=source.CWE,
  AFFECTED_PRODUCTS=source.AFFECTED_PRODUCTS, SOURCE_URL=source.SOURCE_URL,
  INGESTED_AT=CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT
  (CVE_ID,DESCRIPTION,PUBLISHED,LAST_MODIFIED,CVSS_SCORE,SEVERITY,CWE,AFFECTED_PRODUCTS,SOURCE_URL)
VALUES
  (source.CVE_ID,source.DESCRIPTION,source.PUBLISHED,source.LAST_MODIFIED,source.CVSS_SCORE,source.SEVERITY,source.CWE,source.AFFECTED_PRODUCTS,source.SOURCE_URL);
